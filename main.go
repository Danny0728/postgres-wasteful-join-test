package main

import (
	"fmt"
	"log"
	"os"
	"time"

	"gorm.io/driver/postgres"
	"gorm.io/gorm"
	"gorm.io/gorm/logger"
)

type User struct {
	ID      int64
	Name    string
	Address Address
	Orders  []Order
}

type Address struct {
	ID     int64
	UserID int64
	City   string
}

type Order struct {
	ID        int64
	UserID    int64
	Total     float64
	CreatedAt time.Time
	User      User
}

// A variant is one way of writing the same task in GORM:
// fetch every order placed by a user who lives in Pune.
type variant struct {
	name  string
	build func(tx *gorm.DB) *gorm.DB
}

func main() {
	// docker-compose.yml sets DSN. The fallback is for running outside Docker.
	dsn := os.Getenv("DSN")
	if dsn == "" {
		dsn = "host=localhost user=postgres password=pass dbname=postgres port=5432 sslmode=disable"
	}

	// The logger is silent because this program prints the SQL itself.
	db, err := gorm.Open(postgres.Open(dsn), &gorm.Config{
		Logger: logger.Default.LogMode(logger.Silent),
	})
	if err != nil {
		log.Fatal(err)
	}

	variants := []variant{
		{
			// GORM's own association joins. Nothing here is hand-written SQL
			// except the filter on the joined table's alias.
			name: `1. Association joins: Joins("User").Joins("User.Address")`,
			build: func(tx *gorm.DB) *gorm.DB {
				var orders []Order
				return tx.
					Joins("User").
					Joins("User.Address").
					Where(`"User__Address"."city" = ?`, "Pune").
					Find(&orders)
			},
		},
		{
			// A join written by hand as a string, straight to addresses.
			name: "2. Hand-written join string",
			build: func(tx *gorm.DB) *gorm.DB {
				var orders []Order
				return tx.
					Joins("JOIN addresses ON addresses.user_id = orders.user_id").
					Where("addresses.city = ?", "Pune").
					Find(&orders)
			},
		},
		{
			// A subquery on addresses.
			name: "3. Subquery: user_id IN (SELECT ...)",
			build: func(tx *gorm.DB) *gorm.DB {
				var orders []Order
				sub := db.Model(&Address{}).Select("user_id").Where("city = ?", "Pune")
				return tx.Where("user_id IN (?)", sub).Find(&orders)
			},
		},
	}

	// Set EXPLAIN=0 to print only the SQL and skip running the plans.
	runExplain := os.Getenv("EXPLAIN") != "0"

	for _, v := range variants {
		fmt.Println("==================================================================")
		fmt.Println(v.name)
		fmt.Println("==================================================================")

		// ToSQL builds the statement without executing it.
		sql := db.ToSQL(v.build)
		fmt.Println("SQL generated by GORM:")
		fmt.Println(sql)
		fmt.Println()

		if !runExplain {
			continue
		}

		fmt.Println("Plan:")
		rows, err := db.Raw("EXPLAIN (ANALYZE, BUFFERS) " + sql).Rows()
		if err != nil {
			fmt.Println("  could not run EXPLAIN:", err)
			fmt.Println()
			continue
		}
		for rows.Next() {
			var line string
			if err := rows.Scan(&line); err != nil {
				log.Fatal(err)
			}
			fmt.Println(line)
		}
		rows.Close()
		fmt.Println()
	}
}
